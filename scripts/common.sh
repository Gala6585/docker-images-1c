#!/usr/bin/env bash
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [[ -f "$REPO_ROOT/.env" ]]; then set -a; source "$REPO_ROOT/.env"; set +a; fi
: "${DOCKER_REGISTRY_URL:=docker.devops.stng.ru/devops/docker-images}"
: "${UBUNTU_VERSION:=22.04}"
: "${ONEC_VERSION:=8.5.1}"
: "${ONEC_FULL_VERSION:=8.5.1.1343}"
: "${OSCRIPT_VERSION:=1.9.4}"
: "${OSCRIPT_SHA256:=1ad0974cd63a3868c9c730716e1364ad75de751105bf67fe218fb2a9d5697a8c}"
: "${VANESSA_RUNNER_VERSION:=2.6.1}"
: "${ALLURE_VERSION:=2.29.0}"
: "${PLATFORM_IMAGE_NAME:=1c-platform}"
: "${VANESSA_RUNNER_IMAGE_NAME:=vanessa-runner}"
: "${VANESSA_ALLURE_IMAGE_NAME:=vanessa-runner-allure}"
: "${INSTALL_OSCRIPT_FROM_LOCAL:=false}"
IMAGE_PREFIX="${DOCKER_REGISTRY_URL%/}"
PLATFORM_TAG="${ONEC_FULL_VERSION}-thin-ubuntu${UBUNTU_VERSION}"
RUNNER_TAG="${ONEC_FULL_VERSION}-vr${VANESSA_RUNNER_VERSION}"
ALLURE_TAG="${ONEC_FULL_VERSION}-vr${VANESSA_RUNNER_VERSION}-allure${ALLURE_VERSION}"
PLATFORM_IMAGE="${IMAGE_PREFIX}/${PLATFORM_IMAGE_NAME}:${PLATFORM_TAG}"
RUNNER_IMAGE="${IMAGE_PREFIX}/${VANESSA_RUNNER_IMAGE_NAME}:${RUNNER_TAG}"
ALLURE_IMAGE="${IMAGE_PREFIX}/${VANESSA_ALLURE_IMAGE_NAME}:${ALLURE_TAG}"
